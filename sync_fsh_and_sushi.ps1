<#
.SYNOPSIS
  Imports FSH files generated by the skills-and-plugins repo (rcm-to-fsh skill)
  into this IG and runs SUSHI.

.PARAMETER SkillsRepo
  Path to a local clone of skills-and-plugins. Default: ..\skills-and-plugins
  If it does not exist, it is cloned from GitHub.

.PARAMETER Pull
  git pull the skills repo before copying.

.PARAMETER SkipSushi
  Only copy the files, do not run SUSHI.

.EXAMPLE
  .\sync_fsh_and_sushi.ps1 -Pull
#>
param(
  [string]$SkillsRepo = (Join-Path $PSScriptRoot '..\skills-and-plugins'),
  [string]$RepoUrl = 'https://github.com/PharmaDataHub/skills-and-plugins',
  [switch]$Pull,
  [switch]$SkipSushi
)

$ErrorActionPreference = 'Stop'

if (-not (Test-Path -LiteralPath $SkillsRepo)) {
  Write-Host "Cloning $RepoUrl -> $SkillsRepo"
  git clone $RepoUrl $SkillsRepo
} elseif ($Pull) {
  git -C $SkillsRepo pull --ff-only
}

$src = Join-Path $SkillsRepo 'input\fsh'
$dst = Join-Path $PSScriptRoot 'input\fsh'
if (-not (Test-Path -LiteralPath $src)) { throw "Source folder not found: $src" }

$files = Get-ChildItem -LiteralPath $src -Filter *.fsh -File
if (-not $files) { throw "No .fsh files in $src" }

foreach ($f in $files) {
  Copy-Item -LiteralPath $f.FullName -Destination $dst -Force
  Write-Host "Copied $($f.Name)"
}

if ($SkipSushi) { return }

if (-not (Get-Command sushi -ErrorAction SilentlyContinue)) {
  throw "SUSHI not found. Install with: npm install -g fsh-sushi"
}
Push-Location $PSScriptRoot
try {
  sushi .
  if ($LASTEXITCODE -ne 0) { throw "SUSHI failed with exit code $LASTEXITCODE" }
} finally { Pop-Location }
